from __future__ import annotations

import hashlib
from pathlib import Path

from .common import ROOT, sha256_file

INPUT_PATHS = (
    "config",
    "scripts/local",
    "updater",
    "manifests",
    "installer",
    # Build sources change the assembled tree, patches, packaging, license
    # index and release metadata.  They are part of the release inputs even
    # though they are not copied into the package.  tests/ is deliberately not
    # included so test-only changes do not force a formal release.
    "build",
    # The reusable build workflow selects the exact assemble/package commands
    # and arguments; editing it can change the archive without touching build/.
    ".github/workflows/build.yml",
    "VERSION",
    # These are copied into every package; changing them must trigger a build.
    "LICENSE",
    "NOTICE",
    "THIRD_PARTY.md",
    "LICENSE_PROVENANCE.md",
)

# Generated by Python or test tooling; never part of a package.
IGNORED_DIRECTORIES = frozenset({"__pycache__", ".pytest_cache", ".mypy_cache", ".ruff_cache"})
IGNORED_SUFFIXES = frozenset({".pyc", ".pyo"})
# Scratch files inside build/ are not packaged and must not perturb the hash.
BUILD_TEMP_SUFFIXES = frozenset({".tmp", ".temp", ".swp", ".swo", ".bak"})


def _is_ignored(path: Path, root: Path) -> bool:
    relative = path.relative_to(root)
    if any(part in IGNORED_DIRECTORIES for part in relative.parts):
        return True
    suffix = path.suffix.lower()
    if suffix in IGNORED_SUFFIXES:
        return True
    if relative.parts and relative.parts[0] == "build" and suffix in BUILD_TEMP_SUFFIXES:
        return True
    return False


def input_files(root: Path = ROOT) -> list[Path]:
    files: list[Path] = []
    for relative in INPUT_PATHS:
        path = root / relative
        if path.is_file():
            files.append(path)
        elif path.is_dir():
            files.extend(
                child
                for child in path.rglob("*")
                if child.is_file() and not _is_ignored(child, root)
            )
    return sorted(set(files), key=lambda item: str(item.relative_to(root)).replace("\\", "/"))


def compute_inputs_hash(root: Path = ROOT) -> str:
    digest = hashlib.sha256()
    for path in input_files(root):
        relative = str(path.relative_to(root)).replace("\\", "/")
        digest.update(relative.encode("utf-8"))
        digest.update(b"\0")
        digest.update(sha256_file(path).encode("ascii"))
        digest.update(b"\n")
    return digest.hexdigest()
